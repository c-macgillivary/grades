"""Integration tests for the implemented grade update/show commands.

Run from the repository root:
    python3 tests/test_grade.py
"""

import os

from UnitTest import TestRunner

EXECUTABLE = os.environ.get("GRADES_EXECUTABLE", "./build/bin/release/grades")


def main() -> int:
    with TestRunner(EXECUTABLE) as test:
        test.run_many(
            [
                # Fixtures.
                (("Create primary grade-test course", "c", "a", "TEST101"),
                 {"stdout_contains": "Successfully added course TEST101"}),
                (("Create an ungraded assessment", "a", "a", "TEST101", "Quiz", "20"),
                 {"stdout_contains": "Successfully added assessment Quiz"}),
                (("Create a graded ratio assessment", "a", "a", "TEST101", "Midterm", "30", "18/20"),
                 {"stdout_contains": "Successfully added assessment Midterm"}),
                (("Create a graded percentage assessment", "a", "a", "TEST101", "Final", "50", "82.5%"),
                 {"stdout_contains": "Successfully added assessment Final"}),

                # Command grammar and required/optional arguments.
                (("Grade parent requires a subcommand", "grade"),
                 {"error": True, "expected_returncode": 106}),
                (("Grade alias requires a subcommand", "g"),
                 {"error": True, "expected_returncode": 106}),
                (("Unknown grade subcommand is rejected", "g", "invalid"),
                 {"error": True, "expected_returncode": 106}),
                (("Update requires all three positional arguments", "g", "update"),
                 {"error": True, "expected_returncode": 106}),
                (("Update requires assessment name and grade", "g", "u", "TEST101"),
                 {"error": True, "expected_returncode": 106}),
                (("Update requires a new grade", "g", "u", "TEST101", "Quiz"),
                 {"error": True, "expected_returncode": 106}),
                (("Show requires a course code", "g", "show"),
                 {"error": True, "expected_returncode": 106}),
                (("Show rejects an extra positional argument", "g", "s", "TEST101", "Quiz", "extra"),
                 {"error": True, "expected_returncode": 109}),
                (("Update rejects an extra positional argument", "g", "u", "TEST101", "Quiz", "80", "extra"),
                 {"error": True, "expected_returncode": 109}),

                # Showing individual assessment grades.
                (("Show ungraded assessment", "g", "s", "TEST101", "Quiz"),
                 {"expected_stdout": "Assessment Quiz in TEST101 has not been completed\n"}),
                (("Show ratio grade in percentage mode", "grade", "show", "TEST101", "Midterm"),
                 {"expected_stdout": "Grade for Midterm in TEST101 is 90%\n"}),
                (("Show percentage-input grade", "g", "s", "TEST101", "Final"),
                 {"expected_stdout": "Grade for Final in TEST101 is 83%\n"}),
                (("Show grade as a score with short flag", "g", "s", "-s", "TEST101", "Midterm"),
                 {"expected_stdout": "Grade for Midterm in TEST101 is 18/20\n"}),
                (("Show grade as a score with long flag", "grade", "show", "--score", "TEST101", "Final"),
                 {"expected_stdout": "Grade for Final in TEST101 is 82.5/100\n"}),
                (("Show alias works for show", "g", "s", "TEST101", "Midterm"),
                 {"expected_stdout": "Grade for Midterm in TEST101 is 90%\n"}),
                (("Showing an unknown assessment reports assessment-not-found", "g", "s", "TEST101", "DoesNotExist"),
                 {"error": True, "stderr_contains": "Assessment DoesNotExist does not exist"}),
                (("Showing an assessment in an unknown course reports course-not-found", "g", "s", "MISSING", "Quiz"),
                 {"error": True, "stderr_contains": "Course MISSING does not exist"}),

                # Grade-input parser: malformed syntax and domain checks.
                (("Reject nonnumeric update input", "g", "u", "TEST101", "Quiz", "abc"),
                 {"error": True, "stderr_contains": 'Invalid input "abc"'}),
                (("Reject empty update input", "g", "u", "TEST101", "Quiz", ""),
                 {"error": True, "stderr_contains": 'Invalid input ""'}),
                (("Reject trailing alphabetic characters", "g", "u", "TEST101", "Quiz", "80abc"),
                 {"error": True, "stderr_contains": 'Invalid input "80abc"'}),
                (("Reject trailing whitespace", "g", "u", "TEST101", "Quiz", "80 "),
                 {"error": True, "stderr_contains": 'Invalid input "80 "'}),
                (("Reject percent sign followed by more text", "g", "u", "TEST101", "Quiz", "80%x"),
                 {"error": True, "stderr_contains": 'Invalid input "80%x"'}),
                (("Reject repeated percent signs", "g", "u", "TEST101", "Quiz", "80%%"),
                 {"error": True, "stderr_contains": 'Invalid input "80%%"'}),
                (("Reject multiple ratio separators", "g", "u", "TEST101", "Quiz", "80/100/2"),
                 {"error": True, "stderr_contains": 'Invalid input "80/100/2"'}),
                (("Reject empty numerator", "g", "u", "TEST101", "Quiz", "/100"),
                 {"error": True, "stderr_contains": 'Invalid input "/100"'}),
                (("Reject empty denominator", "g", "u", "TEST101", "Quiz", "80/"),
                 {"error": True, "stderr_contains": 'Invalid input "80/"'}),
                (("Reject percent suffix on a ratio", "g", "u", "TEST101", "Quiz", "80/100%"),
                 {"error": True, "stderr_contains": 'Invalid input "80/100%"'}),
                (("Reject negative percentage grade", "g", "u", "TEST101", "Quiz", "-1"),
                 {"error": True, "stderr_contains": "Input must be a non-negative value"}),
                (("Reject negative ratio numerator", "g", "u", "TEST101", "Quiz", "-1/20"),
                 {"error": True, "stderr_contains": "Input must be a non-negative value"}),
                (("Reject zero ratio denominator", "g", "u", "TEST101", "Quiz", "80/0"),
                 {"error": True, "stderr_contains": "Denominator must be positive"}),
                (("Reject negative ratio denominator", "g", "u", "TEST101", "Quiz", "80/-20"),
                 {"error": True, "stderr_contains": "Denominator must be positive"}),
                (("Invalid grade parsing occurs before course lookup", "g", "u", "MISSING", "Quiz", "bad"),
                 {"error": True, "stderr_contains": 'Invalid input "bad"',
                  "stderr_not_contains": "Course MISSING does not exist"}),
                (("Rejected update inputs leave the existing assessment ungraded", "g", "s", "TEST101", "Quiz"),
                 {"expected_stdout": "Assessment Quiz in TEST101 has not been completed\n"}),

                # Valid update forms, boundaries, rounding, and previous-grade reporting.
                (("Update an ungraded assessment using a ratio", "g", "u", "TEST101", "Quiz", "17/20"),
                 {"expected_stdout": "Added grade 85% to assessment Quiz in TEST101\n"}),
                (("Show newly assigned grade", "g", "s", "TEST101", "Quiz"),
                 {"expected_stdout": "Grade for Quiz in TEST101 is 85%\n"}),
                (("Update an existing grade using a ratio", "grade", "update", "TEST101", "Quiz", "179/200"),
                 {"expected_stdout": "Grade for Quiz in TEST101 updated from 85% to 90%\n"}),
                (("Rounding uses nearest integer for update messages", "g", "u", "TEST101", "Quiz", "89.4%"),
                 {"expected_stdout": "Grade for Quiz in TEST101 updated from 90% to 89%\n"}),
                (("Update to the same grade still reports an update", "g", "u", "TEST101", "Quiz", "89.4"),
                 {"expected_stdout": "Grade for Quiz in TEST101 updated from 89% to 89%\n"}),
                (("Update grade to zero", "g", "u", "TEST101", "Quiz", "0"),
                 {"expected_stdout": "Grade for Quiz in TEST101 updated from 89% to 0%\n"}),
                (("Show zero grade", "g", "s", "TEST101", "Quiz"),
                 {"expected_stdout": "Grade for Quiz in TEST101 is 0%\n"}),
                (("Grades above 100 percent are accepted", "g", "u", "TEST101", "Quiz", "25/20"),
                 {"expected_stdout": "Grade for Quiz in TEST101 updated from 0% to 125%\n"}),
                (("Show grade above 100 percent", "g", "s", "TEST101", "Quiz"),
                 {"expected_stdout": "Grade for Quiz in TEST101 is 125%\n"}),
                (("Score mode preserves the entered ratio", "g", "s", "-s", "TEST101", "Quiz"),
                 {"expected_stdout": "Grade for Quiz in TEST101 is 25/20\n"}),
                (("A leading space before a number is accepted", "g", "u", "TEST101", "Quiz", " 50"),
                 {"expected_stdout": "Grade for Quiz in TEST101 updated from 125% to 50%\n"}),
                (("Scientific notation is accepted", "g", "u", "TEST101", "Quiz", "1e2"),
                 {"expected_stdout": "Grade for Quiz in TEST101 updated from 50% to 100%\n"}),
                (("Explicit plus sign is accepted", "g", "u", "TEST101", "Quiz", "+5"),
                 {"expected_stdout": "Grade for Quiz in TEST101 updated from 100% to 5%\n"}),
                (("Valid update is persisted and remains showable", "g", "s", "TEST101", "Quiz"),
                 {"expected_stdout": "Grade for Quiz in TEST101 is 5%\n"}),

                # Error paths in update: parsing happens before manager lookup.
                (("Updating unknown course with valid grade reports course-not-found", "g", "u", "MISSING", "Quiz", "80"),
                 {"error": True, "stderr_contains": ("Could not update grade", "Course MISSING does not exist")}),
                (("Updating unknown assessment reports assessment-not-found", "g", "u", "TEST101", "Unknown", "80"),
                 {"error": True, "stderr_contains": ("Could not update grade", "Assessment Unknown does not exist")}),
                (("Missing course wins over missing assessment on update", "g", "u", "MISSING", "Unknown", "80"),
                 {"error": True, "stderr_contains": "Course MISSING does not exist",
                  "stderr_not_contains": "Assessment Unknown does not exist"}),
                (("Failed updates to missing entities leave existing grade unchanged", "g", "s", "TEST101", "Quiz"),
                 {"expected_stdout": "Grade for Quiz in TEST101 is 5%\n"}),

                # Course-level current-grade behaviour.
                (("Create course with no assessments", "c", "a", "EMPTY"),
                 {"stdout_contains": "Successfully added course EMPTY"}),
                (("Current grade with no assessments is undefined", "g", "s", "EMPTY"),
                 {"error": True, "stderr_contains": ("Could not show current grade in EMPTY", "Invalid current grade: 0/0")}),
                (("Create course containing only ungraded assessments", "c", "a", "UNMARKED"),
                 {"stdout_contains": "Successfully added course UNMARKED"}),
                (("Add an ungraded-only assessment", "a", "a", "UNMARKED", "Homework", "50"),
                 {"stdout_contains": "Successfully added assessment Homework"}),
                (("Current grade with only ungraded assessments is undefined", "g", "s", "UNMARKED"),
                 {"error": True, "stderr_contains": ("Could not show current grade in UNMARKED", "Invalid current grade: 0/0")}),
                (("Create course for current-grade ratio test", "c", "a", "CURRENT"),
                 {"stdout_contains": "Successfully added course CURRENT"}),
                (("Add a 100-weight assessment graded at 80 percent", "a", "a", "CURRENT", "Exam", "100", "80"),
                 {"stdout_contains": "Successfully added assessment Exam"}),
                (("Current grade is the percentage earned on a single assessment", "g", "s", "CURRENT"),
                 {"expected_stdout": "Current grade in CURRENT is 80%\n"}),
                (("Exact course current grade prints the unrounded percentage", "grade", "show", "--exact", "CURRENT"),
                 {"expected_stdout": "Current grade in CURRENT is 80%\n"}),
                (("Short exact flag does the same", "g", "s", "-e", "CURRENT"),
                 {"expected_stdout": "Current grade in CURRENT is 80%\n"}),
                (("Score flag displays the current grade as a score", "g", "s", "-s", "CURRENT"),
                 {"expected_stdout": "Current grade in CURRENT is 80/100\n"}),
                (("Create course for multi-assessment current-grade calculation", "c", "a", "WEIGHTED"),
                 {"stdout_contains": "Successfully added course WEIGHTED"}),
                (("Add first graded assessment to calculation test", "a", "a", "WEIGHTED", "A", "1", "75"),
                 {"stdout_contains": "Successfully added assessment A"}),
                (("Add second graded assessment to calculation test", "a", "a", "WEIGHTED", "B", "3", "50"),
                 {"stdout_contains": "Successfully added assessment B"}),
                (("Current grade is the weighted average of graded assessments", "g", "s", "-e", "WEIGHTED"),
                 {"expected_stdout": "Current grade in WEIGHTED is 56.25%\n"}),
                (("Default output rounds the weighted average", "g", "s", "WEIGHTED"),
                 {"expected_stdout": "Current grade in WEIGHTED is 56%\n"}),
                (("Create course for partially marked weighting test", "c", "a", "PARTIAL"),
                 {"stdout_contains": "Successfully added course PARTIAL"}),
                (("Add graded half-weight assessment", "a", "a", "PARTIAL", "Marked", "50", "80"),
                 {"stdout_contains": "Successfully added assessment Marked"}),
                (("Add ungraded half-weight assessment", "a", "a", "PARTIAL", "NotMarked", "50"),
                 {"stdout_contains": "Successfully added assessment NotMarked"}),
                (("Ungraded assessment weights are excluded from the denominator", "g", "s", "-e", "PARTIAL"),
                 {"expected_stdout": "Current grade in PARTIAL is 80%\n"}),
                (("Score mode shows earned weighted points over graded weight", "g", "s", "-s", "PARTIAL"),
                 {"expected_stdout": "Current grade in PARTIAL is 40/50\n"}),
                (("Create course with a zero-weight graded assessment", "c", "a", "ZERO_WEIGHT"),
                 {"stdout_contains": "Successfully added course ZERO_WEIGHT"}),
                (("Add graded zero-weight assessment", "a", "a", "ZERO_WEIGHT", "Zero", "0", "80"),
                 {"stdout_contains": "Successfully added assessment Zero"}),
                (("Current grade with only zero assessed weight is undefined", "g", "s", "ZERO_WEIGHT"),
                 {"error": True, "stderr_contains": ("Could not show current grade in ZERO_WEIGHT", "Invalid current grade: 0/0")}),
                (("Current grade unknown course reports course-not-found", "g", "s", "MISSING"),
                 {"error": True, "stderr_contains": ("Could not show current grade in MISSING", "Course MISSING does not exist")}),
            ]
        )

        return test.summary()


if __name__ == "__main__":
    raise SystemExit(main())
