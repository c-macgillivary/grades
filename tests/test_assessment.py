"""Integration tests for the currently implemented assessment operations.

Run from the repository root:
    python3 tests/test_assessments.py
"""

import os

from UnitTest import TestRunner

EXECUTABLE = os.environ.get("GRADES_EXECUTABLE", "./build/bin/release/grades")


def main() -> int:
    with TestRunner(EXECUTABLE) as test:
        test.run_many(
            [
                # Set up and test command grammar.
                (("Create the assessment test course", "c", "a", "CS145"),
                 {"stdout_contains": "Successfully added course CS145"}),
                (("Assessments parent requires a subcommand", "assessment"),
                 {"error": True, "expected_returncode": 106}),
                (("Assessments alias requires a subcommand", "a"),
                 {"error": True, "expected_returncode": 106}),
                (("Unknown assessment subcommand is rejected", "a", "invalid"),
                 {"error": True, "expected_returncode": 106}),
                (("Add requires all positional arguments", "a", "add"),
                 {"error": True, "expected_returncode": 106}),
                (("Add requires course and assessment names", "a", "a", "CS145"),
                 {"error": True, "expected_returncode": 106}),
                (("Add requires a weight", "a", "add", "CS145", "Quiz"),
                 {"error": True, "expected_returncode": 106}),
                (("Add accepts an optional grade", "a", "add", "CS145", "OptionalGrade", "10"),
                 {"stdout_contains": "Successfully added assessment OptionalGrade"}),
                (("Add rejects excess arguments after optional grade", "a", "a", "CS145", "Extra", "10", "80", "extra"),
                 {"error": True, "expected_returncode": 109}),
                (("Remove requires both positional arguments", "a", "remove"),
                 {"error": True, "expected_returncode": 106}),
                (("Remove requires an assessment name after the course", "a", "remove", "CS145"),
                 {"error": True, "expected_returncode": 106}),
                (("Remove rejects excess arguments", "a", "r", "CS145", "Quiz", "extra"),
                 {"error": True, "expected_returncode": 109}),

                # Assessment name validation is only an all-whitespace check.
                (("Empty assessment name is rejected", "a", "a", "CS145", "", "10"),
                 {"error": True, "stderr_contains": "is an invalid assessment name"}),
                (("Spaces-only assessment name is rejected", "a", "a", "CS145", "   ", "10"),
                 {"error": True, "stderr_contains": "is an invalid assessment name"}),
                (("All common whitespace-only names are rejected", "a", "a", "CS145", " \t\n\r\v\f", "10"),
                 {"error": True, "stderr_contains": "is an invalid assessment name"}),
                (("Name validation occurs before weight parsing", "a", "a", "CS145", " \t ", "not-a-weight"),
                 {"error": True,
                  "stderr_contains": "is an invalid assessment name",
                  "stderr_not_contains": "Invalid input"}),
                (("Assessment names may contain internal spaces", "a", "a", "CS145", "Lab Report 1", "10"),
                 {"stdout_contains": "Successfully added assessment Lab Report 1"}),
                (("Assessment names may contain punctuation", "a", "a", "CS145", "Quiz-1/Part-A", "10"),
                 {"stdout_contains": "Successfully added assessment Quiz-1/Part-A"}),
                (("Non-whitespace assessment names may have surrounding spaces", "a", "a", "CS145", " Quiz ", "10"),
                 {"stdout_contains": "Successfully added assessment  Quiz "}),

                # Weight parsing: syntax and the numeric-domain checks in parseInput.
                (("Malformed weight text is rejected", "a", "a", "CS145", "BadWeight1", "abc"),
                 {"error": True, "stderr_contains": 'Invalid input "abc"'}),
                (("Empty weight text is rejected", "a", "a", "CS145", "BadWeight2", ""),
                 {"error": True, "stderr_contains": 'Invalid input ""'}),
                (("Weight with trailing letters is rejected", "a", "a", "CS145", "BadWeight3", "20abc"),
                 {"error": True, "stderr_contains": 'Invalid input "20abc"'}),
                (("Weight with trailing whitespace is rejected", "a", "a", "CS145", "BadWeight4", "20 "),
                 {"error": True, "stderr_contains": 'Invalid input "20 "'}),
                (("Weight with misplaced percent sign is rejected", "a", "a", "CS145", "BadWeight5", "20%x"),
                 {"error": True, "stderr_contains": 'Invalid input "20%x"'}),
                (("Weight with repeated percent signs is rejected", "a", "a", "CS145", "BadWeight6", "20%%"),
                 {"error": True, "stderr_contains": 'Invalid input "20%%"'}),
                (("Weight with multiple slashes is rejected", "a", "a", "CS145", "BadWeight7", "20/10/2"),
                 {"error": True, "stderr_contains": 'Invalid input "20/10/2"'}),
                (("Weight with empty numerator is rejected", "a", "a", "CS145", "BadWeight8", "/20"),
                 {"error": True, "stderr_contains": 'Invalid input "/20"'}),
                (("Weight with empty denominator is rejected", "a", "a", "CS145", "BadWeight9", "20/"),
                 {"error": True, "stderr_contains": 'Invalid input "20/"'}),
                (("Weight with percent suffix after a fraction is rejected", "a", "a", "CS145", "BadWeight10", "20/30%"),
                 {"error": True, "stderr_contains": 'Invalid input "20/30%"'}),
                (("Negative scalar weight is rejected", "a", "a", "CS145", "NegativeWeight1", "-1"),
                 {"error": True, "stderr_contains": "Input must be a non-negative value"}),
                (("Negative fraction numerator is rejected", "a", "a", "CS145", "NegativeWeight2", "-1/20"),
                 {"error": True, "stderr_contains": "Input must be a non-negative value"}),
                (("Zero denominator is rejected", "a", "a", "CS145", "ZeroDenominator", "20/0"),
                 {"error": True, "stderr_contains": "Denominator must be positive"}),
                (("Negative denominator is rejected", "a", "a", "CS145", "NegativeDenominator", "20/-5"),
                 {"error": True, "stderr_contains": "Denominator must be positive"}),
                (("Malformed weight attempts do not insert assessments", "d"),
                 {"stdout_not_contains": ("BadWeight1", "BadWeight2", "BadWeight3", "BadWeight4", "BadWeight5", "BadWeight6", "BadWeight7", "BadWeight8", "BadWeight9", "BadWeight10", "NegativeWeight1", "NegativeWeight2", "ZeroDenominator", "NegativeDenominator")}),

                # Valid forms and boundaries. The pair-based Weight::create currently
                # does not enforce part <= total, so weights above 100% are accepted.
                (("Add zero-percent weight", "a", "a", "CS145", "ZeroWeight", "0"),
                 {"stdout_contains": "Successfully added assessment ZeroWeight"}),
                (("Add 100-percent scalar weight", "a", "a", "CS145", "FullWeight", "100"),
                 {"stdout_contains": "Successfully added assessment FullWeight"}),
                (("Add percent weight with percent suffix", "a", "a", "CS145", "PercentWeight", "12.5%"),
                 {"stdout_contains": "Successfully added assessment PercentWeight"}),
                (("Add ratio-form weight", "a", "a", "CS145", "RatioWeight", "25.5/30"),
                 {"stdout_contains": "Successfully added assessment RatioWeight"}),
                (("Add weight above 100 using scalar input (current accepted behaviour)", "a", "a", "CS145", "OverweightScalar", "150"),
                 {"error": True, "stderr_contains": ("Could not add assessment OverweightScalar", "Invalid weight")}),
                (("Add weight above 100 using ratio input (current accepted behaviour)", "a", "a", "CS145", "OverweightRatio", "150/100"),
                 {"error": True, "stderr_contains": ("Could not add assessment OverweightRatio", "Invalid weight")}),
                (("Leading whitespace before a number is accepted by stod", "a", "a", "CS145", "LeadingSpaceWeight", " 7"),
                 {"stdout_contains": "Successfully added assessment LeadingSpaceWeight"}),
                (("Scientific notation is accepted for weight", "a", "a", "CS145", "ScientificWeight", "1e1"),
                 {"stdout_contains": "Successfully added assessment ScientificWeight"}),
                (("Explicit plus sign is accepted for weight", "a", "a", "CS145", "PlusWeight", "+5"),
                 {"stdout_contains": "Successfully added assessment PlusWeight"}),
                (("Add an assessment with a percentage grade", "a", "a", "CS145", "PercentGrade", "10", "87.5%"),
                 {"stdout_contains": "Successfully added assessment PercentGrade"}),
                (("Add an assessment with a ratio grade", "assessment", "add", "CS145", "RatioGrade", "10/20", "17/20"),
                 {"stdout_contains": "Successfully added assessment RatioGrade"}),
                (("Add an assessment with a grade above 100 percent (accepted)", "a", "a", "CS145", "GradeAbove100", "10", "25/20"),
                 {"stdout_contains": "Successfully added assessment GradeAbove100"}),
                (("An explicitly empty optional grade is treated as ungraded", "a", "a", "CS145", "EmptyGrade", "10", ""),
                 {"stdout_contains": "Successfully added assessment EmptyGrade"}),
                (("Malformed grade syntax is rejected before insertion", "a", "a", "CS145", "BadOptionalGrade", "10", "80oops"),
                 {"error": True, "stderr_contains": 'Invalid input "80oops"'}),
                (("Negative optional grade is rejected", "a", "a", "CS145", "NegativeOptionalGrade", "10", "-1"),
                 {"error": True, "stderr_contains": "Input must be a non-negative value"}),
                (("Zero denominator in optional grade is rejected", "a", "a", "CS145", "ZeroGradeDenominator", "10", "80/0"),
                 {"error": True, "stderr_contains": "Denominator must be positive"}),
                (("Optional grade with multiple slashes is rejected", "a", "a", "CS145", "BadRatioGrade", "10", "1/2/3"),
                 {"error": True, "stderr_contains": 'Invalid input "1/2/3"'}),
                (("Invalid optional-grade attempts do not create assessments", "d"),
                 {"stdout_not_contains": ("BadOptionalGrade", "NegativeOptionalGrade", "ZeroGradeDenominator", "BadRatioGrade")}),
                (("Invalid optional grade is not inserted", "d"),
                 {"stdout_not_contains": '"BadOptionalGrade"',
                  "stdout_contains": ('"PercentGrade"', '"RatioGrade"', '"GradeAbove100"')}),

                # Error precedence and manager-level lookups.
                (("Invalid weight is reported before missing-course lookup", "a", "a", "MISSING", "MissingCourseBadWeight", "oops"),
                 {"error": True, "stderr_contains": 'Invalid input "oops"',
                  "stderr_not_contains": "Course MISSING does not exist"}),
                (("Valid assessment input for missing course reports course-not-found", "a", "a", "MISSING", "Quiz", "10"),
                 {"error": True, "stderr_contains": "Course MISSING does not exist"}),
                (("Whitespace-only course code on add assessment reports course-not-found", "a", "a", "   ", "Quiz", "10"),
                 {"error": True, "stderr_contains": "Course     does not exist"}),
                (("Duplicate assessment name is rejected", "a", "a", "CS145", "PercentGrade", "5"),
                 {"error": True,
                  "stderr_contains": ("Could not add assessment", "Assessment PercentGrade already exists")}),
                (("Duplicate is checked after parsing the new weight", "a", "a", "CS145", "PercentGrade", "oops"),
                 {"error": True, "stderr_contains": 'Invalid input "oops"',
                  "stderr_not_contains": "already exists"}),
                (("Assessment names are case-sensitive", "a", "a", "CS145", "percentgrade", "5"),
                 {"stdout_contains": "Successfully added assessment percentgrade"}),
                (("Case-distinct assessment names both exist", "dump"),
                 {"stdout_occurrences": {'"PercentGrade"': 2, '"percentgrade"': 2}}),

                # Remove semantics and state preservation.
                (("Remove from missing course reports course-not-found", "a", "r", "MISSING", "Quiz"),
                 {"error": True,
                  "stderr_contains": ("Could not remove assessment", "Course MISSING does not exist")}),
                (("Missing course error takes precedence over missing assessment", "a", "r", "MISSING", "Unknown"),
                 {"error": True, "stderr_contains": "Course MISSING does not exist",
                  "stderr_not_contains": "Assessment Unknown does not exist"}),
                (("Remove nonexistent assessment reports assessment-not-found", "a", "r", "CS145", "Unknown"),
                 {"error": True, "stderr_contains": "Assessment Unknown does not exist"}),
                (("Remove empty assessment name is a not-found error", "a", "r", "CS145", ""),
                 {"error": True, "stderr_contains": "Assessment  does not exist"}),
                (("Remove is case-sensitive", "a", "r", "CS145", "PERCENTGRADE"),
                 {"error": True, "stderr_contains": "Assessment PERCENTGRADE does not exist"}),
                (("Remove assessment by its exact full name", "assessment", "remove", "CS145", "PercentGrade"),
                 {"stdout_contains": "Successfully removed assessment PercentGrade"}),
                (("Removed assessment is absent from dump", "d"),
                 {"stdout_not_contains": '"PercentGrade"',
                  "stdout_contains": '"percentgrade"'}),
                (("Remove same assessment twice fails", "a", "r", "CS145", "PercentGrade"),
                 {"error": True, "stderr_contains": "Assessment PercentGrade does not exist"}),
                (("Remove case-distinct assessment separately", "a", "r", "CS145", "percentgrade"),
                 {"stdout_contains": "Successfully removed assessment percentgrade"}),
                (("Remove an assessment whose name contains spaces", "a", "r", "CS145", "Lab Report 1"),
                 {"stdout_contains": "Successfully removed assessment Lab Report 1"}),
                (("Remove an assessment whose name contains punctuation", "a", "r", "CS145", "Quiz-1/Part-A"),
                 {"stdout_contains": "Successfully removed assessment Quiz-1/Part-A"}),
                (("Remove the assessment with surrounding spaces exactly", "a", "r", "CS145", " Quiz "),
                 {"stdout_contains": "Successfully removed assessment  Quiz "}),
                (("Other assessments remain after removals", "dump"),
                 {"stdout_contains": ('"ZeroWeight"', '"FullWeight"', '"GradeAbove100"', '"OptionalGrade"'),
                  "stdout_not_contains": ('"PercentGrade"', '"Lab Report 1"', '"Quiz-1/Part-A"')}),
            ]
        )

        return test.summary()


if __name__ == "__main__":
    raise SystemExit(main())
